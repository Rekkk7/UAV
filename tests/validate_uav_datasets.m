function report = validate_uav_datasets(dataset_root, check_main_scripts)
%VALIDATE_UAV_DATASETS Check the shared instances without running algorithms.
%   REPORT = VALIDATE_UAV_DATASETS() validates all 81 MAT files in the
%   project's datasets directory and checks the ten experiment entry points.
%   REPORT = VALIDATE_UAV_DATASETS(ROOT, false) validates another generated
%   dataset directory without checking experiment scripts.
%
%   Comparisons use the loaded MATLAB values, not MAT-file binary headers.
%   This function restores the MATLAB path and caller's random-number state.

    project_root = fileparts(fileparts(mfilename('fullpath')));
    default_dataset_root = fullfile(project_root, 'datasets');
    if nargin < 1 || isempty(dataset_root)
        dataset_root = default_dataset_root;
    end
    if nargin < 2
        check_main_scripts = true;
    end
    if isstring(dataset_root)
        dataset_root = char(dataset_root);
    end
    require(ischar(dataset_root) && isfolder(dataset_root), ...
        'Dataset directory does not exist: %s', dataset_root);
    require(isscalar(check_main_scripts) && ...
        (islogical(check_main_scripts) || isnumeric(check_main_scripts)), ...
        'check_main_scripts must be a scalar logical value.');

    original_path = path;
    path_cleanup = onCleanup(@() path(original_path)); %#ok<NASGU>
    original_rng = rng;
    rng_cleanup = onCleanup(@() rng(original_rng)); %#ok<NASGU>
    addpath(default_dataset_root);

    [~, root_attributes] = fileattrib(dataset_root);
    [~, default_attributes] = fileattrib(default_dataset_root);
    dataset_root = root_attributes.Name;
    use_shared_loader = strcmpi(dataset_root, default_attributes.Name);

    configs = uav_dataset_configs();
    expected_names = {'Small-Scale', 'Medium-Scale', 'Large-Scale'};
    expected_folders = {'小规模', '中规模', '大规模'};
    expected_prefixes = {'S', 'M', 'L'};
    require(isstruct(configs) && numel(configs) == 3, ...
        'uav_dataset_configs must return three scale configurations.');
    require(all(isfield(configs, {'name', 'folder', 'prefix', 'instances'})), ...
        'Scale configurations are missing required fields.');

    all_files = dir(fullfile(dataset_root, '**', '*.mat'));
    require(numel(all_files) == 81, ...
        'Expected exactly 81 MAT files; found %d in %s.', ...
        numel(all_files), dataset_root);

    expected_fields = {'Task_num', 'Target_num', 'UAV_num', 'Location', ...
        'Speed_UAV', 'Task_require_UAV', 'H', 'N', 'Task_lo', ...
        'Task_type', 'Pre', 'theta', 'EM0', 'T_max', 'seed', ...
        'base_seed', 'rng_algorithm', 'instance_index', 'run_index', ...
        'scale_name', 'schema_version'};
    snapshots = cell(81, 1);
    records = struct('scale_name', {}, 'target', {}, 'uav', {}, ...
        'run_index', {}, 'file_path', {});
    seeds = zeros(81, 1);
    scale_counts = zeros(1, 3);
    configuration_counts = zeros(3, 9);
    cursor = 0;
    common_base_seed = [];
    common_schema_version = [];
    common_rng_algorithm = [];

    for scale_index = 1:3
        config = configs(scale_index);
        require(strcmp(config.name, expected_names{scale_index}) && ...
            strcmp(config.folder, expected_folders{scale_index}) && ...
            strcmp(config.prefix, expected_prefixes{scale_index}), ...
            'Unexpected name, folder, or prefix for scale %d.', scale_index);
        require(isequal(size(config.instances), [9, 2]) && ...
            all(isfinite(config.instances(:))) && ...
            all(config.instances(:) >= 1) && ...
            all(config.instances(:) == fix(config.instances(:))) && ...
            size(unique(config.instances, 'rows'), 1) == 9, ...
            '%s must contain nine distinct positive integer configurations.', ...
            config.name);

        scale_folder = fullfile(dataset_root, config.folder);
        scale_files = dir(fullfile(scale_folder, '*.mat'));
        require(isfolder(scale_folder) && numel(scale_files) == 27, ...
            'Expected 27 MAT files directly in %s; found %d.', ...
            scale_folder, numel(scale_files));

        for instance_index = 1:9
            target_count = config.instances(instance_index, 1);
            uav_count = config.instances(instance_index, 2);
            instance_pattern = sprintf('%s_T%03d_U%03d_R*.mat', ...
                config.prefix, target_count, uav_count);
            instance_files = dir(fullfile(scale_folder, instance_pattern));
            require(numel(instance_files) == 3, ...
                'Expected three runs for %s, T=%d, U=%d; found %d.', ...
                config.name, target_count, uav_count, numel(instance_files));

            for run_index = 1:3
                cursor = cursor + 1;
                file_name = sprintf('%s_T%03d_U%03d_R%02d.mat', ...
                    config.prefix, target_count, uav_count, run_index);
                file_path = fullfile(scale_folder, file_name);
                require(isfile(file_path), 'Missing instance: %s', file_path);

                before_load = rng;
                data = load(file_path);
                require(isequaln(before_load, rng), ...
                    'Loading a MAT file changed RNG state: %s', file_path);
                require(all(isfield(data, expected_fields)), ...
                    'Missing top-level instance fields in %s.', file_path);
                validate_instance(data, target_count, uav_count, ...
                    scale_index, instance_index, run_index, config.name, file_path);

                if cursor == 1
                    common_base_seed = data.base_seed;
                    common_schema_version = data.schema_version;
                    common_rng_algorithm = data.rng_algorithm;
                else
                    require(isequaln(data.base_seed, common_base_seed), ...
                        'Inconsistent base_seed in %s.', file_path);
                    require(isequaln(data.schema_version, common_schema_version), ...
                        'Inconsistent schema_version in %s.', file_path);
                    require(isequaln(data.rng_algorithm, common_rng_algorithm), ...
                        'Inconsistent rng_algorithm in %s.', file_path);
                end

                before_create = rng;
                regenerated = create_uav_instance(config.name, target_count, ...
                    uav_count, run_index, data.base_seed);
                require(isequaln(before_create, rng), ...
                    'create_uav_instance changed caller RNG state for %s.', file_path);
                require(isequaln(data, regenerated), ...
                    'Loaded values differ from deterministic regeneration: %s', file_path);

                record = struct('scale_name', config.name, ...
                    'target', target_count, 'uav', uav_count, ...
                    'run_index', run_index, 'file_path', file_path);
                before_loader = rng;
                loaded = load_record(record, use_shared_loader);
                require(isequaln(before_loader, rng), ...
                    'Instance loader changed caller RNG state for %s.', file_path);
                require(isequaln(data, loaded), ...
                    'Instance loader returned different values for %s.', file_path);

                snapshots{cursor} = data;
                records(cursor) = record; %#ok<AGROW>
                seeds(cursor) = double(data.seed);
                scale_counts(scale_index) = scale_counts(scale_index) + 1;
                configuration_counts(scale_index, instance_index) = ...
                    configuration_counts(scale_index, instance_index) + 1;
            end
        end
    end

    require(cursor == 81 && all(scale_counts == 27) && ...
        all(configuration_counts(:) == 3), ...
        'Dataset coverage is not 81 files / 27 per scale / 3 per configuration.');
    require(numel(unique(seeds)) == 81, ...
        'All 81 instance seeds must be distinct.');

    % A second pass reverses scale, configuration, and run loading order.
    % It does not draw random values to decide the order.
    for record_index = cursor:-1:1
        before_load = rng;
        reloaded = load_record(records(record_index), use_shared_loader);
        require(isequaln(before_load, rng), ...
            'Reverse-order loading changed RNG state: %s', ...
            records(record_index).file_path);
        require(isequaln(reloaded, snapshots{record_index}), ...
            'Loading order affected the instance: %s', records(record_index).file_path);
    end

    scripts_checked = 0;
    if check_main_scripts
        scripts_checked = validate_main_scripts(project_root);
    end
    require(isequaln(original_rng, rng), ...
        'Dataset validation changed the caller RNG state.');

    report = struct('dataset_root', dataset_root, 'file_count', cursor, ...
        'scale_counts', scale_counts, ...
        'configuration_counts', configuration_counts, ...
        'unique_seed_count', numel(unique(seeds)), ...
        'base_seed', common_base_seed, ...
        'regeneration_matches', true, 'rng_preserved', true, ...
        'load_order_independent', true, ...
        'shared_loader_checked', use_shared_loader, ...
        'main_scripts_checked', scripts_checked);
    fprintf(['Dataset validation passed: %d files, 27 per scale, ', ...
        '3 per configuration, %d unique seeds, %d main scripts.\n'], ...
        cursor, numel(unique(seeds)), scripts_checked);
end

function validate_instance(data, targets, uavs, scale_index, instance_index, ...
        run_index, scale_name, file_path)
    tasks = 2 * targets;
    require(isequal(data.Task_num, tasks) && ...
        isequal(data.Target_num, targets) && isequal(data.UAV_num, uavs), ...
        'Incorrect task, target, or UAV count in %s.', file_path);
    require(integer_matrix(data.Location, [targets + uavs, 2], 1, 100), ...
        'Location dimensions or range are incorrect in %s.', file_path);
    require(integer_matrix(data.Speed_UAV, [uavs, 1], 1, 10), ...
        'Speed_UAV dimensions or range are incorrect in %s.', file_path);
    require(integer_matrix(data.H, [tasks, uavs], 10, 25), ...
        'H dimensions or range are incorrect in %s.', file_path);
    require(isequal(data.Task_require_UAV, ones(1, tasks)), ...
        'Each task must require exactly one UAV in %s.', file_path);
    require(integer_matrix(data.N, [tasks, uavs], 0, 1) && ...
        all(sum(data.N, 2) == 1), ...
        'N must have exactly one eligible UAV per task in %s.', file_path);

    expected_locations = reshape(repmat(1:targets, 2, 1), 1, []);
    expected_types = repmat([1, 2], 1, targets);
    expected_pre = zeros(tasks, tasks);
    expected_pre(sub2ind([tasks, tasks], 2:2:tasks, 1:2:tasks)) = 1;
    expected_theta = targets + (1:uavs);
    expected_initial_state = {zeros(1, tasks), zeros(uavs, tasks), ...
        zeros(uavs, tasks), expected_theta, zeros(1, uavs), cell(1, uavs)};
    require(isequal(data.Task_lo, expected_locations), ...
        'Task-to-target mapping is incorrect in %s.', file_path);
    require(isequal(data.Task_type, expected_types), ...
        'Task types must alternate first/second stage in %s.', file_path);
    require(isequal(data.Pre, expected_pre), ...
        'The two-stage predecessor matrix is incorrect in %s.', file_path);
    require(isequal(data.theta, expected_theta), ...
        'Initial UAV locations are incorrect in %s.', file_path);
    require(isequaln(data.EM0, expected_initial_state), ...
        'Initial scheduling state EM0 is incorrect in %s.', file_path);
    require(isequal(data.T_max, uavs * targets / 10), ...
        'T_max must equal UAV_num * Target_num / 10 in %s.', file_path);
    require(numeric_integer_scalar(data.base_seed) && data.base_seed >= 0, ...
        'Invalid base_seed in %s.', file_path);
    require(numeric_integer_scalar(data.seed) && ...
        data.seed == data.base_seed + scale_index * 10000 + instance_index * 100 + run_index, ...
        'Seed does not match the scale/configuration/run formula in %s.', file_path);
    require(isequal(data.instance_index, instance_index) && ...
        isequal(data.run_index, run_index) && strcmp(data.scale_name, scale_name), ...
        'Instance metadata does not match its file/configuration in %s.', file_path);
    require((ischar(data.rng_algorithm) || ...
        (isstring(data.rng_algorithm) && isscalar(data.rng_algorithm))) && ...
        ~isempty(char(data.rng_algorithm)), ...
        'rng_algorithm must be a nonempty text value in %s.', file_path);
    require(~isempty(data.schema_version), ...
        'schema_version must not be empty in %s.', file_path);
end

function valid = integer_matrix(value, dimensions, lower_bound, upper_bound)
    valid = isnumeric(value) && isreal(value) && isequal(size(value), dimensions) && ...
        all(isfinite(value(:))) && all(value(:) == fix(value(:))) && ...
        all(value(:) >= lower_bound) && all(value(:) <= upper_bound);
end

function valid = numeric_integer_scalar(value)
    valid = isnumeric(value) && isreal(value) && isscalar(value) && ...
        isfinite(value) && value == fix(value);
end

function data = load_record(record, use_shared_loader)
    if use_shared_loader
        data = load_uav_instance(record.scale_name, record.target, ...
            record.uav, record.run_index);
    else
        data = load(record.file_path);
    end
end

function scripts_checked = validate_main_scripts(project_root)
    main_files = dir(fullfile(project_root, '*', 'main.m'));
    require(numel(main_files) == 10, ...
        'Expected ten experiment main.m files; found %d.', numel(main_files));
    for file_index = 1:numel(main_files)
        file_path = fullfile(main_files(file_index).folder, main_files(file_index).name);
        source = fileread(file_path);
        % These entry points use ordinary line comments; remove block comments
        % too so historical experiment snippets are not treated as active code.
        source = regexprep(source, '(?ms)^\s*%\{.*?^\s*%\}\s*$', '');
        active_source = regexprep(source, '(?m)%[^\r\n]*', '');
        run_assignments = regexp(active_source, ...
            'num_runs_per_instance\s*=\s*([^;\r\n]+)', 'tokens');
        require(numel(run_assignments) == 1 && ...
            strcmp(strtrim(run_assignments{1}{1}), '3'), ...
            'main.m must set num_runs_per_instance to 3 exactly once: %s', file_path);
        require(~isempty(regexp(active_source, ...
            '\<load_uav_instance\s*\(', 'once')), ...
            'main.m does not load shared instances: %s', file_path);
        require(isempty(regexp(active_source, ...
            '\<(rand|randi|randn|randperm|rng)\s*\(', 'once')), ...
            'main.m still contains active random-data generation: %s', file_path);
    end
    scripts_checked = numel(main_files);
end

function require(condition, message, varargin)
    if ~condition
        error('UAV:DatasetValidationFailed', message, varargin{:});
    end
end
